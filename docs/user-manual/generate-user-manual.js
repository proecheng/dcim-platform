function H1(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 400, after: 200 }, children: [new TextRun({ text, bold: true, size: 36, font: 'Microsoft YaHei' })] });
}
function H2(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 300, after: 150 }, children: [new TextRun({ text, bold: true, size: 30, font: 'Microsoft YaHei' })] });
}
function H3(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_3, spacing: { before: 200, after: 100 }, children: [new TextRun({ text, bold: true, size: 26, font: 'Microsoft YaHei' })] });
}
function P(text) {
  return new Paragraph({ spacing: { after: 120 }, children: [new TextRun({ text, size: 22, font: 'Microsoft YaHei' })] });
}
function PBold(text) {
  return new Paragraph({ spacing: { after: 120 }, children: [new TextRun({ text, bold: true, size: 22, font: 'Microsoft YaHei' })] });
}
function B(items) {
  return items.map(t => new Paragraph({ numbering: { reference: 'bullets', level: 0 }, spacing: { after: 60 }, children: [new TextRun({ text: t, size: 22, font: 'Microsoft YaHei' })] }));
}
function N(items) {
  return items.map(t => new Paragraph({ numbering: { reference: 'numbers', level: 0 }, spacing: { after: 60 }, children: [new TextRun({ text: t, size: 22, font: 'Microsoft YaHei' })] }));
}
function STEPS(items) {
  return items.map(t => new Paragraph({ numbering: { reference: 'steps', level: 0 }, spacing: { after: 60 }, children: [new TextRun({ text: t, size: 22, font: 'Microsoft YaHei' })] }));
}
function BREAK() {
  return new Paragraph({ children: [new PageBreak()] });
}
function IMG(filename) {
  const fp = path.join(SCREENSHOT_DIR, filename);
  if (!fs.existsSync(fp)) { console.warn('\u622a\u56fe\u4e0d\u5b58\u5728: ' + filename); return []; }
  const data = fs.readFileSync(fp);
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 200, after: 100 }, children: [
      new ImageRun({ type: 'png', data, transformation: { width: 680, height: 383 }, altText: { title: filename, description: filename, name: filename } })
    ] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 150 }, children: [new TextRun({ text: '\u56fe\uff1a' + filename.replace('.png','').replace(/-/g,' '), size: 18, font: 'Microsoft YaHei', italics: true, color: '666666' })] }),
  ];
}
function NOTE(text) {
  return new Paragraph({ spacing: { before: 100, after: 100 }, indent: { left: 400 }, children: [
    new TextRun({ text: '\u26a0 \u6ce8\u610f\uff1a', bold: true, size: 22, font: 'Microsoft YaHei', color: 'CC6600' }),
    new TextRun({ text, size: 22, font: 'Microsoft YaHei', color: '666666' }),
  ] });
}
function TIP(text) {
  return new Paragraph({ spacing: { before: 100, after: 100 }, indent: { left: 400 }, children: [
    new TextRun({ text: '\u2139 \u63d0\u793a\uff1a', bold: true, size: 22, font: 'Microsoft YaHei', color: '0066CC' }),
    new TextRun({ text, size: 22, font: 'Microsoft YaHei', color: '666666' }),
  ] });
}


